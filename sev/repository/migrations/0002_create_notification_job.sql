CREATE TABLE IF NOT EXISTS `notification_job` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `notification_id` VARCHAR(64) NOT NULL,
    `request_id` VARCHAR(128) NOT NULL,
    `business` VARCHAR(64) NOT NULL,
    `endpoint_code` VARCHAR(128) NOT NULL,
    `payload` JSON NOT NULL,
    `request_url` VARCHAR(2048) NOT NULL,
    `request_method` VARCHAR(16) NOT NULL,
    `request_headers` JSON NULL,
    `request_body` MEDIUMTEXT NULL,
    `content_type` VARCHAR(32) NOT NULL,
    `timeout_ms` INT NOT NULL DEFAULT 5000,
    `status` VARCHAR(32) NOT NULL,
    `fail_reason` VARCHAR(64) NULL,
    `retry_count` INT NOT NULL DEFAULT 0,
    `max_retry_count` INT NOT NULL DEFAULT 10,
    `next_retry_at` DATETIME NULL,
    `locked_until` DATETIME NULL,
    `http_status` INT NULL,
    `last_error` VARCHAR(2048) NULL,
    `created_at` DATETIME NOT NULL,
    `updated_at` DATETIME NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_notification_id` (`notification_id`),
    UNIQUE KEY `uk_business_request` (`business`, `request_id`),
    KEY `idx_endpoint_code` (`endpoint_code`),
    KEY `idx_retry` (`status`, `next_retry_at`),
    KEY `idx_processing` (`status`, `locked_until`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
